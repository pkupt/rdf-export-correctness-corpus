def dump(name, rows, hdr):
    p = os.path.join(OUT, name)
    with open(p, "w", newline="", encoding="utf-8") as f:
        w = csv.writer(f)
        w.writerow(hdr)
        for r in rows:
            w.writerow(list(r))
    print("wrote", p, len(rows), "rows")

