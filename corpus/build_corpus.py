def annotate(rows):
    """Insert the trigger column before the trailing `notes` column."""
    out = []
    for r in rows:
        r = list(r)
        trig = TRIGGERS.get((r[0], r[2]), "")
        note = r[-1]
        if (r[0], r[2]) in RETEST_NOT_REPRODUCED:
            note = (note + " | " if note else "") + RETEST_NOTE
        out.append(r[:-1] + [trig, note])
    return out

